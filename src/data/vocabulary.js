export const ALL = [];
(() => {
  let ch = 0;
  RAW.split('\n').forEach((line) => {
    const l = line.trim();
    if (!l) return;
    if (l[0] === '#') {
      ch = parseInt(l.slice(1), 10);
      return;
    }
    const p = l.split('|');
    ALL.push({ g: p[0].trim(), e: p[1].trim(), ch });
  });
})();

export const CHAPTERS = Array.from({ length: 23 }, (_, i) => i + 1);
